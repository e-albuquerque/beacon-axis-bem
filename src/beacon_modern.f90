PP6=XA*(YP-YQ)/(XP*XC*XD)
PP7=XA/(XP*XC*XD)
PP8=XA*(YP-YQ)/(XQ*XC*XD)
PP9=XA/(XQ*XC*XD)
PP10=2.*XA*(YP-YQ)/(XC*XD)
