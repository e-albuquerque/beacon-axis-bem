SUBROUTINE SHAPE(H)
  use beacon_state
  implicit none
  real :: h
!--PURPOSE : TO CALCULATE SHAPE FUNCTIONS AND THEIR DERIVATIVES.
SHAPF(1)=0.5*H*(H-1.0)
SHAPF(2)=1.0-H**2
SHAPF(3)=0.5*H*(H+1.0)
SHAPD(1)=H-0.5
SHAPD(2)=-2.0*H
SHAPD(3)=H+0.5
RETURN
END
