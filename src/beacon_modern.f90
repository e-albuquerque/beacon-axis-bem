SUBROUTINE INTCAL
  use beacon_state
  implicit none
  integer :: i, ic, ig, irow1, irow2
  real :: diff, duxdr, duxdz, duydr, duydz, fact, h, rad, resul, sigma1, sigma2, sigma3, sigmae, toler, tr, tz, ux, uy, xe, xn1, xx1, xx2
!--PURPOSE : TO CALCULATE THE INTERNAL DISPLACEMENTS AND STRESSES.
IF(NINPTS.EQ.0)RETURN

DO NODEP=1,NINPTS
XP=XINT(NODEP)
YP=YINT(NODEP)

TOLER=1.E-20
DIFF=0.5-XNU
IF(DIFF.LT.TOLER)XNU=0.5-TOLER
RAD=XP/DMAX
IF(IGEOM.EQ.1.AND.RAD.LT.TOLER)XP=TOLER*DMAX

UXINT(NODEP)=0.0
UYINT(NODEP)=0.0
SXXINT(NODEP)=0.0
SXYINT(NODEP)=0.0
SYYINT(NODEP)=0.0
DUXDR=0.0
DUXDZ=0.0
DUYDR=0.0
DUYDZ=0.0

DO IELEMQ=1,NELEMS
CALL ARRAY3(IELEMQ)
DO IC=1,3
NODEQ=NORDER(IC)
IROW1=2*NODEQ-1
IROW2=IROW1+1
UX=U(IROW1)
UY=U(IROW2)
TR=XTRAC(IELEMQ,IC)
TZ=YTRAC(IELEMQ,IC)

DO IG=1,NGAUSS
H=XG(IG)
CALL SHAPE(H)
CALL JACOBI(NODEQ)

ISELF=0
IF(IGEOM.EQ.1)CALL KERAXI
IF(IGEOM.EQ.1)FACT=2.0*PI*XJACOB*CG(IG)*SHAPF(IC)*XQ
IF(IGEOM.NE.1)CALL KER2D
IF(IGEOM.NE.1)FACT=XJACOB*CG(IG)*SHAPF(IC)

UXINT(NODEP)=UXINT(NODEP)+FACT*(-UX*TXX-UY*TXY+TR*UXX+TZ*UXY)
UYINT(NODEP)=UYINT(NODEP)+FACT*(-UX*TYX-UY*TYY+TR*UYX+TZ*UYY)

IF(IGEOM.EQ.1)CALL DIFFAX
IF(IGEOM.NE.1)CALL DIFF2D

IF(IGEOM.NE.1)THEN
SXXINT(NODEP)=SXXINT(NODEP)+FACT*(-S1XX*UX-S2XX*UY+D1XX*TR+D2XX*TZ)
SXYINT(NODEP)=SXYINT(NODEP)+FACT*(-S1XY*UX-S2XY*UY+D1XY*TR+D2XY*TZ)
SYYINT(NODEP)=SYYINT(NODEP)+FACT*(-S1YY*UX-S2YY*UY+D1YY*TR+D2YY*TZ)
ENDIF

IF(IGEOM.EQ.1)THEN
DUXDR=DUXDR+FACT*(-UX*DTXXDR-UY*DTXYDR+TR*DUXXDR+TZ*DUXYDR)
DUXDZ=DUXDZ+FACT*(-UX*DTXXDZ-UY*DTXYDZ+TR*DUXXDZ+TZ*DUXYDZ)
DUYDR=DUYDR+FACT*(-UX*DTYXDR-UY*DTYYDR+TR*DUYXDR+TZ*DUYYDR)
DUYDZ=DUYDZ+FACT*(-UX*DTYXDZ-UY*DTYYDZ+TR*DUYXDZ+TZ*DUYYDZ)
ENDIF
4 END DO
3 END DO
2 END DO

IF(IGEOM.EQ.1)THEN
XN1=XNU/(1.0-2.0*XNU)
XE=DUXDR+DUYDZ+UXINT(NODEP)/XP
SXXINT(NODEP)=2.0*XMU*(DUXDR+XN1*XE)
SYYINT(NODEP)=2.0*XMU*(DUYDZ+XN1*XE)
SXYINT(NODEP)=XMU*(DUXDZ+DUYDR)
SZZINT(NODEP)=2.0*XMU*(UXINT(NODEP)/XP+XN1*XE)
ENDIF

IF(IGEOM.EQ.2)SZZINT(NODEP)=XNU*(SXXINT(NODEP)+SYYINT(NODEP))
IF(IGEOM.EQ.3)SZZINT(NODEP)=0.0
1 END DO

!--OUTPUT INTERNAL DISPLACEMENTS.
WRITE(6,61)
61 FORMAT(//2X,'INTERNAL DISPLACEMENTS')
DO NODEP=1,NINPTS
RESUL=SQRT(UXINT(NODEP)**2+UYINT(NODEP)**2)
WRITE(6,62)NODEP,XINT(NODEP),YINT(NODEP),UXINT(NODEP),UYINT(NODEP),RESUL
5 END DO
62 FORMAT(1X,I5,5(1X,1PE12.4))

!--OUTPUT INTERNAL STRESSES.
WRITE(6,63)
63 FORMAT(//2X,'INTERNAL STRESSES')
DO I=1,NINPTS
XX1=0.5*(SXXINT(I)+SYYINT(I))
XX2=0.5*SQRT((SXXINT(I)-SYYINT(I))**2+4.0*SXYINT(I)**2)
SIGMA1=XX1+XX2
SIGMA2=XX1-XX2
SIGMA3=SZZINT(I)
SIGMAE=SQRT((SIGMA1-SIGMA2)**2+(SIGMA2-SIGMA3)**2+(SIGMA1-SIGMA3)**2)/SQRT(2.0)
WRITE(6,64)I,SXXINT(I),SYYINT(I),SXYINT(I),SZZINT(I),SIGMAE
6 END DO
64 FORMAT(1X,I5,5(1X,1PE12.4))

RETURN
END
