SUBROUTINE JACOBI(NODE)
  use beacon_state
  implicit none
  integer :: ic, node
  real :: dxdh, dydh
!--PURPOSE : TO CALCULATE THE JACOBIAN AND THE UNIT NORMAL COMPONENTS.
DXDH=0.0
DYDH=0.0
DO IC=1,3
DXDH=DXDH+SHAPD(IC)*CORDX(IC)
DYDH=DYDH+SHAPD(IC)*CORDY(IC)
1 END DO
XJACOB=SQRT(DXDH**2+DYDH**2)
IF(XJACOB.LT.1.E-10)THEN
WRITE(6,61)NODE
61 FORMAT(//78(1H*)//2X,'** ERROR **'/2X,'THE JACOBIAN IS ZERO AT NODE ',I4/2X,'THIS MAY BE CAUSED BY COINCIDENT NODES OR ZERO-LENGTH ELEMENTS'/2X,'** PROGRAM HALTED **'//78(1H*)//)
STOP
ENDIF
XNORM=DYDH/XJACOB
YNORM=-DXDH/XJACOB
RETURN
END
