XX2=1./XP+DCDR/XC
XX3=-2.*XC*XN1*DCDR
XX4=DBDR-XB*DDDR/XD
XX5=-XN1*XC**2-ZZ*XB/XD
XX6=(YP-YQ)*(2.*XB+(YP-YQ)*(DBDZ-XB*DDDZ/XD))/XD
XX7=2.*XN1*XC*DCDZ
XX8=1.-(YP-YQ)*DCDZ/XC
XX9=DCDR/XC+DDDR/XD
XX10=XB*DFDR+XF*DBDR-XB*XF*DDDR/XD-2.*XB*XF*DCDR/XC
XX11=1./XP+DCDR/XC
XX12=2.*XNU*XM-1.5*XN+.5*XB*XF*ZZ/XDC2
XX13=XF*(YP-YQ)*DBDZ+XB*(YP-YQ)*DFDZ+2.*XB*XF
XX14=.5*XB*XF*ZZ*(2.*DCDZ/XC+DDDZ/XD)/XDC2
XX15=DCDZ*XX12/XC
XX16=XP*XP*DSDR+2.*XS*XP+ZZ*DVDR
XX17=3.*XP*XP*DFDR+6.*XP*XF+3.*ZZ*DXMDR
XX18=2.*XB*XB*XF*ZZ*(DDDR/XD+2.*DCDR/XC)/XDC2
XX19=2.*XB*ZZ*(XB*DFDR+2.*XF*DBDR)/XDC2
XX20=1./XP+DCDR/XC+DDDR/XD
XX21=XP*XP*XS+ZZ*XV+XQ**4
XX22=3.*(XP*XP*XF+ZZ*XM)-2.*XB*XB*XF*ZZ/XDC2
XX23=-2.*XNU*XX21+XX22
XX24=XP*XP*DSDZ+ZZ*DVDZ+2.*(YP-YQ)*XV
XX25=3.*XP*XP*DFDZ+3.*ZZ*DXMDZ+6.*XM*(YP-YQ)
XX26=2.*XB*XB*XF*ZZ*(DDDZ/XD+2.*DCDZ/XC)/XDC2
XX27=XB*(YP-YQ)*DFDZ+2.*XF*(YP-YQ)*DBDZ+2.*XB*XF
XX28=2.*XB*(YP-YQ)*XX27/XDC2
XX29=(DCDZ/XC+DDDZ/XD)*XX23
XX30=DBDR-2.*XB*DCDR/XC
XX31=1./XP+DCDR/XC+DDDR/XD
XX32=(YP-YQ)*DBDZ+2.*XB-2.*XB*(YP-YQ)*DCDZ/XC
XX33=1.-(YP-YQ)*DCDZ/XC-(YP-YQ)*DDDZ/XD
XX34=XN4*XD+XB*ZZ/XC**2
XX35=2.*DBDR-XB*DDDR/XD-2.*XB*DCDR/XC
XX36=1./XP+DCDR/XC+DDDR/XD
XX37=3.*ZZ-XN4*XB-4.*XB*XB*ZZ/XDC2
XX38=4.*XB*ZZ*((YP-YQ)*(XB*DDDZ/XD+2.*XB*DCDZ/XC-2.*DBDZ)-2.*XB)/XDC2
XX39=ZZ*(DHDR-2.*XH*DCDR/XC)/XC**2
XX40=DCDR/XC+DDDR/XD
XX41=-XN3*XD+XH*ZZ/XC**2
XX42=2.*XH+(YP-YQ)*DHDZ-2.*XH*(YP-YQ)*DCDZ/XC
XX43=DCDZ/XC+DDDZ/XD
XX44=8.*XF*XP*XP*ZZ*(DDDR/XD+2.*DCDR/XC)/XDC2
XX45=8.*XP*ZZ*(XP*DFDR+2.*XF)/XDC2
XX46=-ZZ+XN3*XH+8.*XF*XP*XP*ZZ/XDC2
XX47=2.*XF*(YP-YQ)*DCDZ/XC+XF*(YP-YQ)*DDDZ/XD-2.*XF-(YP-YQ)*DFDZ
XX48=8.*XP*XP*(YP-YQ)*XX47/XDC2
XX49=XD/XQ**2+2.*ZZ/XC**2
XX50=4.*ZZ*(1.-(YP-YQ)*DCDZ/XC)/XC**2
XX51=1.-(YP-YQ)*XX43
XX52=2.*XB*DCDR/XC+XB*DDDR/XD-DBDR
XX53=4.*(1.+XNU)-XB/XQ**2-8.*XB*ZZ/XDC2
XX54=(YP-YQ)*(2.*XB*DCDZ/XC+XB*DDDZ/XD-DBDZ)-2.*XB
XX55=DFDR-2.*XF*DCDR/XC
XX56=-XN3*XD-XF*ZZ/XC**2
XX57=2.*XF*(YP-YQ)*DCDZ/XC-2.*XF-(YP-YQ)*DFDZ
XX58=XB*DFDR+XF*DBDR-XB*XF*DDDR/XD-2.*XB*XF*DCDR/XC
XX59=-3.*ZZ+XN3*XF+4.*XB*XF*ZZ/XDC2
XX60=2.*XB*XF+(YP-YQ)*(XF*DBDZ+XB*DFDZ-XB*XF*DDDZ/XD-2.*XB*XF*DCDZ/XC)
XX61=DBDR-XB*DDDR/XD-2.*XB*DCDR/XC
XX62=XN3+4.*XB*ZZ/XDC2
XX63=2.*XB+(YP-YQ)*(DBDZ-2.*XB*DCDZ/XC-XB*DDDZ/XD)
!--
!- - CALCULATE THE DIFFERENTIALS OF THE DISPLACEMENT KERNELS.
DRRKDR=PP1*(2.*XN1*XP-XX1*XX2)
DRRKDZ=PP1*(8.*XN2*(YP-YQ)-DCDZ*XX1/XC)
DRREDR=PP1*(XX3-ZZ*XX4/XD-XX2*XX5)
DRREDZ=PP1*(-XX7-XX6-XX5*DCDZ/XC)
