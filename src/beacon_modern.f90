62 FORMAT(2X,'MAXIMUM NUMBER OF ELEMENTS       = ',I4,/2X,'MAXIMUM NUMBER OF NODES          = ',I4,/2X,'MAXIMUM NUMBER OF INTERNAL POINTS= ',I4,/)

!--READ THE INPUT DATA FILE.
CALL INPDAT
!--CALCULATE THE NORMAL ANGLES AT EACH NODE.
CALL ANGLES
!--SELECT NUMERICAL DATA FOR GAUSSIAN INTEGRATION AND ELLIPTIC TERMS.
CALL NUMDAT
!--ASSEMBLE THE SOLUTION MATRIX.
CALL ASSEMB
!--SOLVE THE SYSTEM OF LINEAR EQUATIONS.
CALL SOLVER
!--ARRANGE THE COMPUTED VARIABLES IN SUITABLE ARRAYS.
CALL ARRANG
!--CALCULATE THE BOUNDARY STRESSES.
CALL BSTRES
!--OUTPUT ALL VARIABLES.
CALL OUTVAR
!--CALCULATE THE INTERNAL DISPLACEMENTS AND STRESSES.
CALL INTCAL

WRITE(6,63)
63 FORMAT(///,78(1H=)/10X,'COMPLETE PROGRAM RUN',/78(1H=)////)
STOP
END
