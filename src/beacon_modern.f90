DNDR=4.*XP
DNDZ=6.*(YP-YQ)
DSDR=4.*XP
DSDZ=8.*(YP-YQ)
DVDR=0.
DVDZ=4.*(YP-YQ)
!--
DMDR=(SQRT(XP*XQ)/XC)*(-2.0*(XP+XQ)/XC**2+1.0/XP)
