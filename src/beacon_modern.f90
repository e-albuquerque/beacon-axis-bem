SUBROUTINE KER2D
  use beacon_state
  implicit none
  real :: drdn, drdx, drdy, rdist, s1, xa, xb, xn1, xn2
!--PURPOSE : TO CALCULATE THE 2D KERNELS.
XQ=SHAPF(1)*CORDX(1)+SHAPF(2)*CORDX(2)+SHAPF(3)*CORDX(3)
YQ=SHAPF(1)*CORDY(1)+SHAPF(2)*CORDY(2)+SHAPF(3)*CORDY(3)

XA=1.0/(8.0*PI*XMU*(1.0-XNU))
RDIST=SQRT((XP-XQ)**2+(YP-YQ)**2)
XN1=3.0-4.0*XNU
XN2=1.0-2.0*XNU
DRDX=(XQ-XP)/RDIST
DRDY=(YQ-YP)/RDIST
DRDN=DRDX*XNORM+DRDY*YNORM

!--DISPLACEMENT KERNELS, P NOT INSIDE ELEMENT.
IF(ISELF.EQ.0)UXX=XA*(XN1*ALOG(1.0/RDIST)+DRDX*DRDX)
IF(ISELF.EQ.0)UXY=XA*DRDX*DRDY
IF(ISELF.EQ.0)UYX=UXY
IF(ISELF.EQ.0)UYY=XA*(XN1*ALOG(1.0/RDIST)+DRDY*DRDY)

!--DISPLACEMENT KERNELS, P INSIDE ELEMENT (NON-LOG PART).
IF(ISELF.EQ.1.AND.ILOG.EQ.0)S1=-0.5*ALOG(FN1*FN1+FN2*FN2)
IF(ISELF.EQ.1.AND.ILOG.EQ.0)UXX=XA*(XN1*S1+DRDX*DRDX)
IF(ISELF.EQ.1.AND.ILOG.EQ.0)UXY=XA*DRDX*DRDY
IF(ISELF.EQ.1.AND.ILOG.EQ.0)UYX=UXY
IF(ISELF.EQ.1.AND.ILOG.EQ.0)UYY=XA*(XN1*S1+DRDY*DRDY)

!--DISPLACEMENT KERNELS, P INSIDE ELEMENT (LOG PART ONLY).
IF(ISELF.EQ.1.AND.ILOG.EQ.1)UXX=XA*XN1
IF(ISELF.EQ.1.AND.ILOG.EQ.1)UXY=0.0
IF(ISELF.EQ.1.AND.ILOG.EQ.1)UYX=UXY
IF(ISELF.EQ.1.AND.ILOG.EQ.1)UYY=XA*XN1

!--TRACTION KERNELS.
XB=-1.0/(4.0*PI*RDIST*(1.0-XNU))
TXX=XB*DRDN*(XN2+2.0*DRDX*DRDX)
TXY=XB*(DRDN*2.0*DRDX*DRDY-XN2*(DRDX*YNORM-DRDY*XNORM))
TYX=XB*(DRDN*2.0*DRDX*DRDY-XN2*(DRDY*XNORM-DRDX*YNORM))
TYY=XB*DRDN*(XN2+2.0*DRDY*DRDY)

IF(ISELF.EQ.1.AND.ILOG.EQ.1)TXX=0.0
IF(ISELF.EQ.1.AND.ILOG.EQ.1)TXY=0.0
IF(ISELF.EQ.1.AND.ILOG.EQ.1)TYX=0.0
IF(ISELF.EQ.1.AND.ILOG.EQ.1)TYY=0.0
RETURN
END
