PROGRAM BEACON
  use beacon_state
  implicit none
!--DEFINE THE MAXIMUM NUMBER OF NODES, ELEMENTS AND INTERNAL POINTS.
MAXELE=100
MAXNOD=2*MAXELE
MAXINT=200
!--DEFINE PI.
PI=4.0*ATAN(1.0)
!--DEFINE THE LOCAL INTRINSIC COORDINATE PARAMETER (-1,0,+1).
ZETA(1)=-1.0
ZETA(2)=0.0
ZETA(3)=1.0

WRITE(6,61)
61 FORMAT(//78(1H=)/2X,'BEACON - BOUNDARY ELEMENTS IN CONTINUUM',/2X,'2D AND AXISYMMETRIC QUADRATIC ELEMENTS',/78(1H=))
