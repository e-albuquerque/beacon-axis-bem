SUBROUTINE ANGLES
  use beacon_state
  implicit none
  integer :: ic, ielem, node
  real :: ang, h, theta, toler
!--PURPOSE : TO CALCULATE THE ANGLE OF THE OUTWARD NORMAL AT EACH NODE.
TOLER=1.E-20
DO IELEM=1,NELEMS
CALL ARRAY3(IELEM)
DO IC=1,3
NODE=NORDER(IC)
H=ZETA(IC)
CALL SHAPE(H)
CALL JACOBI(NODE)
IF(ABS(XNORM).LT.TOLER)XNORM=TOLER
IF(ABS(YNORM).LT.TOLER)YNORM=TOLER
THETA=ATAN(ABS(YNORM)/ABS(XNORM))
ANG=0.0
IF(XNORM.GT.0.0.AND.YNORM.GT.0.0)ANG=THETA
IF(XNORM.LT.0.0.AND.YNORM.GT.0.0)ANG=PI-THETA
IF(XNORM.GT.0.0.AND.YNORM.LT.0.0)ANG=2.0*PI-THETA
IF(XNORM.LT.0.0.AND.YNORM.LT.0.0)ANG=PI+THETA
ANGNOR(IELEM,IC)=ANG
2 END DO
1 END DO
RETURN
END
