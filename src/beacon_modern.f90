SUBROUTINE ELLIPT
  use beacon_state
  implicit none
  integer :: i
  real :: bm, suma1, sumb1, sumc1, sumd1
!--PURPOSE : TO CALCULATE THE ELLIPTIC INTEGRALS REQUIRED FOR
!--AXISYMMETRIC KERNELS.
!--USE THE A,B,C AND D COEFFICIENTS TO CALCULATE THE ELLIPTIC
!--INTEGRALS, SEE EQ.(2.88) AND (2.89).
BM=1.0-AM*AM
SUMA1=0.0
SUMB1=0.0
SUMC1=0.0
SUMD1=0.0
DO I=1,5
SUMA1=SUMA1+AA1(I)*BM**I
SUMB1=SUMB1+BB1(I)*BM**I
SUMC1=SUMC1+CC1(I)*BM**I
SUMD1=SUMD1+DD1(I)*BM**I
1 END DO

!--"P" IS NOT INSIDE THE ELEMENT "IELEMQ".
IF(ISELF.EQ.0)ELLIPK=ALOG(4.0)+SUMA1+ALOG(1.0/BM)*(0.5+SUMB1)
IF(ISELF.EQ.0)ELLIPE=1.0+SUMC1+ALOG(1.0/BM)*SUMD1

!--"P" IS INSIDE THE ELEMENT "IELEMQ", NON-LOGARITHMIC PARTS.
IF(ISELF.EQ.1.AND.ILOG.EQ.0)ELLIPK=ALOG(4.0)+SUMA1+SI*(0.5+SUMB1)
IF(ISELF.EQ.1.AND.ILOG.EQ.0)ELLIPE=1.0+SUMC1+SI*SUMD1

!--"P" IS INSIDE THE ELEMENT "IELEMQ", LOGARITHMIC PARTS ONLY.
!--NOTE: THESE PARTS ARE ALREADY DIVIDED BY ALOG(1.0/ETA).
IF(ISELF.EQ.1.AND.ILOG.EQ.1)ELLIPK=1.0+2.0*SUMB1
IF(ISELF.EQ.1.AND.ILOG.EQ.1)ELLIPE=2.0*SUMD1
RETURN
END
