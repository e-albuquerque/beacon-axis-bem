DZRKDZ=PP5*XX8
DZREDR=PP6*(XH*DCDR/XC+XH*DDDR/XD+XH/XP-DHDR)
DZREDZ=PP7*(XH*(YP-YQ)*XX43-XH-(YP-YQ)*DHDZ)
DRZKDR=XA*(YP-YQ)*DCDR/(XQ*XC**2)
DRZKDZ=XA*((YP-YQ)*DCDZ/XC-1.)/(XQ*XC)
DRZEDR=PP8*(DFDR-XF*DCDR/XC-XF*DDDR/XD)
DRZEDZ=PP9*(XF+(YP-YQ)*DFDZ-(YP-YQ)*XF*(DCDZ/XC+DDDZ/XD))
