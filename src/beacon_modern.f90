SUBROUTINE DIFF2D
  use beacon_state
  implicit none
  real :: drdn, drdx, drdy, rdist, xaa, xbb, xn1, xn2, xn3
!-- PURPOSE : TO CALCULATE THE DIFFERENTIALS OF THE 2D KERNELS.
!--
! -CALCULATE THE COORDINATES OF THE ELEMENT "IELEMQ".
XQ=SHAPF(1)*CORDX(1)+SHAPF(2)*CORDX(2)+SHAPF(3)*CORDX(3)
YQ=SHAPF(1)*CORDY(1)+SHAPF(2)*CORDY(2)+SHAPF(3)*CORDY(3)
!--
RDIST=SQRT((XP-XQ)**2+(YP-YQ)**2)
DRDX=(XQ-XP)/RDIST
DRDY=(YQ-YP)/RDIST
DRDN=DRDX*XNORM+DRDY*YNORM
!--
!- -CALCULATE THE D(KIJ) KERNELS, SEE EQ.(4.38).
XAA=1./(4.*PI*(1.-XNU)*RDIST)
XN1=1.-2.*XNU
D1XX=XAA*DRDX*(XN1+2.*DRDX*DRDX)
D2XX=XAA*DRDY*(-XN1+2.*DRDX*DRDX)
D1XY=XAA*DRDY*(XN1+2.*DRDX*DRDX)
D2XY=XAA*DRDX*(XN1+2.*DRDY*DRDY)
D1YY=XAA*DRDX*(-XN1+2.*DRDY*DRDY)
D2YY=XAA*DRDY*(XN1+2.*DRDY*DRDY)
!
!- -CALCULATE THE S(KIJ) KERNELS, SEE EQ.(4.37).
XBB=XMU/(2.*PI*(1.-XNU)*RDIST*RDIST)
XN1=1.-2.*XNU
XN2=1.-4.*XNU
XN3=1.-XNU
S1XX=XBB*(XNORM*(1.+2.*DRDX*DRDX)+2.*DRDN*DRDX*(1.-4.*DRDX*DRDX))
S2XX=XBB*(XNORM*4.*XNU*DRDX*DRDY+YNORM*(2.*XN1*DRDX*DRDX-XN2)+2.*DRDN*DRDY*(XN1-4.*DRDX*DRDX))
S1XY=XBB*(XNORM*2.*XN3*DRDX*DRDY+YNORM*(2.*XNU*DRDX*DRDX+XN1)+2.*DRDN*DRDY*(XNU-4.*DRDX*DRDX))
S2XY=XBB*(XNORM*(2.*XNU*DRDY*DRDY+XN1)+YNORM*2.*XN3*DRDX*DRDY+2.*DRDN*DRDX*(XNU-4.*DRDY*DRDY))
S1YY=XBB*(XNORM*(2.*XN1*DRDY*DRDY-XN2)+YNORM*4.*XNU*DRDX*DRDY+2.*DRDN*DRDX*(XN1-4.*DRDY*DRDY))
S2YY=XBB*(YNORM*(1.+2.*DRDY*DRDY)+2.*DRDN*DRDY*(1.-4.*DRDY*DRDY))
RETURN
END
