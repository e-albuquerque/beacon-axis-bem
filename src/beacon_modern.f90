SUBROUTINE KERAXI
  use beacon_state
  implicit none
  real :: ua1, ua2, ua3, ua4, x1, x2, x3, x4, x5, x6, x7, x8, xa, xa1, xa2, xa3, xa5, xa6, xa7, xc, xd, xdc2, xn1, xn2, xn3, zz
!-PURPOSE : TO CALCULATE THE AX I SYMMETRIC KERNELS.
!--
!-CALCULATE THE COORDINATES OF THE FIELD POINT Q, SEE EQ . (4.39) .
XQ=SHAPF(1)*CORDX(1)+SHAPF(2)*CORDX(2)+SHAPF(3)*CORDX(3)
YQ=SHAPF(1)*CORDY(1)+SHAPF(2)*CORDY(2)+SHAPF(3)*CORDY(3)
!--
!- -CALCULATE SOME COMMON PARAMETERS.
XA=1./(16.*PI*PI*XMU*(1.-XNU))
ZZ=(YP-YQ)**2
XC=SQRT((XP+XQ)**2+ZZ)
XD=(XP-XQ)**2+ZZ
XDC2=XD*XC*XC
AM=2.*SQRT(XP*XQ)/XC
XN1=1.-2.*XNU
XN2=2.*XNU-3.
XN3=3.-4.*XNU
X1=2.*XP**2+XQ**2+2.*ZZ
X2=2.*XP**2+3.*ZZ
X3=XP**2+XQ**2+ZZ
X4=XP**2-XQ**2+ZZ
X5=XQ**2-XP**2+ZZ
X6=2.*XP**2-3.*XQ**2+4.*ZZ
X7=3.*XQ**2+2.*ZZ
X8=ZZ*X3*X4/XDC2
!--
! - -CALCULATE THE COMPONENTS OF THE DISPLACEMENT KERNELS, SEE EQ.(6.33).
UA1=XA/(XP*XQ*XC)
UA2=XA*(YP-YQ)/(XP*XC)
UA3=XA*(YP-YQ)/(XQ*XC)
UA4=2.*XA/XC
!--
! -SPLIT THE DISP. KERNELS INTO THE PARTS THAT MULTIPLY THE
!--ELLIPTIC INTEGRALS K AND E.
UXXK=UA1*(XN3*X3+ZZ)
UXXE=UA1*(-XN3*XC*XC-ZZ*X3/XD)
UXYK=UA2
UXYE=-UA2*X5/XD
UYXK=-UA3
UYXE=UA3*X4/XD
UYYK=UA4*XN3
UYYE=UA4*ZZ/XD
!--
!- -CALCULATE THE COMPONENTS OF THE TRACTION KERNELS, SEE APPENDIX (D) .
XA1=XA/(XP*XQ*XQ*XC)
XA2=(YP-YQ)*XA/(XP*XQ*XC*XD)
XA3=XA/(XP*XC*XD)
XA5=(YP-YQ)*XA/(XC*XD)
XA6=XA/(XQ*XC*XD)
XA7=2.*(YP-YQ)*XA/(XC*XD)
TK1=XA1*(2.*XNU*X1-1.5*X2+0.5*X8)
TE1=(XA1/XD)*(-2.*XNU*(XP*XP*X6+ZZ*X7+XQ**4)+3.*(XP*XP*X4+ZZ*X1)-2.*X8*X3)
TK2=XA2*(XN2*XD+ZZ*X3/(XC*XC))
TE2=XA2*(3.*ZZ-XN2*X3-4.*ZZ*X3*X3/XDC2)
TK3=XA3*(-XN1*XD+ZZ*X5/(XC*XC))
TE3=XA3*(-ZZ+XN1*X5+8.*ZZ*XP*XP*X4/XDC2)
TK4=TK2
TE4=TE2
TK5=XA5*(XD/(XQ*XQ)+2.*ZZ/(XC*XC))
TE5=XA5*(4.*(1.+XNU)-X3/(XQ*XQ)-8.*ZZ*X3/XDC2)
TK6=XA6*(-XN1*XD-ZZ*X4/(XC*XC))
TE6=XA6*(-3.*ZZ+XN1*X4+4.*ZZ*X3*X4/XDC2)
TK7=XA7*(-ZZ/(XC*XC))
TE7=XA7*(XN1+4.*ZZ*X3/XDC2)
TK8=TK6
TE8=TE6
!--
!- -SPLIT THE TRACTION KERNELS INTO THE PARTS THAT MULTIPLY THE
!--ELLITIC INTEGRALS K AND E.
TXXK=2.*XMU*(TK1*XNORM+TK2*YNORM)
TXXE=2.*XMU*(TE1*XNORM+TE2*YNORM)
TXYK=2.*XMU*(TK3*YNORM+TK4*XNORM)
TXYE=2.*XMU*(TE3*YNORM+TE4*XNORM)
TYXK=2.*XMU*(TK5*XNORM+TK6*YNORM)
TYXE=2.*XMU*(TE5*XNORM+TE6*YNORM)
TYYK=2.*XMU*(TK7*YNORM+TK8*XNORM)
TYYE=2.*XMU*(TE7*YNORM+TE8*XNORM)
!--
!--DEFINE THE PARAMETER SI REQUIRED FOR NON-LOGARITHMIC PARTS
!--OF THE ELLIPTIC INTEGRALS.
IF(ISELF.EQ.1.AND.ILOG.EQ.0)SI=ALOG(XC*XC)-ALOG(FN1*FN1+FN2*FN2)
! -
!- -CALCULATE THE ELLIPTIC INTEGRALS,
!--NOTE : THE ELLIPTIC INTEGRALS WILL TAKE CARE OF THE LOGARITHMIC
!-- AND NON-LOGARITHMIC PARTS WHEN P IS INSIDE " IELEMQ" .
CALL ELLIPT
!--
!--NOW CALCULATE A11 THE KERNELS BY MULTIPLYING THEIR COMPONENTS
!--BY THE RELEVANT ELLIPTIC INTEGRALS.
UXX=UXXK*ELLIPK+UXXE*ELLIPE
UXY=UXYK*ELLIPK+UXYE*ELLIPE
UYX=UYXK*ELLIPK+UYXE*ELLIPE
UYY=UYYK*ELLIPK+UYYE*ELLIPE
TXX=TXXK*ELLIPK+TXXE*ELLIPE
TXY=TXYK*ELLIPK+TXYE*ELLIPE
TYX=TYXK*ELLIPK+TYXE*ELLIPE
TYY=TYYK*ELLIPK+TYYE*ELLIPE
RETURN
END
