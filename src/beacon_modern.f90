!--
SUBROUTINE BCAPPL
  use beacon_state
  implicit none
  integer :: ibc, ic, id, ielem, node
  real :: disp
IF(NBCU.EQ.0)GO TO 7771

!--PRESCRIBED DISPLACEMENTS: prepare swapped coefficients in F-arrays.
DO IBC=1,NBCU
IELEM=ISTORU(IBC)
ID=IDIREC(IBC)
CALL ARRAY3(IELEM)
DO IC=1,3
NODE=NORDER(IC)
IF(ID.EQ.1)F11(NODE)=F11(NODE)-B11(IELEM,IC)*SCALEF
IF(ID.EQ.1)F21(NODE)=F21(NODE)-B21(IELEM,IC)*SCALEF
IF(ID.EQ.2)F12(NODE)=F12(NODE)-B12(IELEM,IC)*SCALEF
IF(ID.EQ.2)F22(NODE)=F22(NODE)-B22(IELEM,IC)*SCALEF
2 END DO
1 END DO

DO NODE=1,NNODES
NCHECK(NODE)=0
3 END DO

!--Move prescribed displacement terms to RHS and replace A by F.
DO IBC=1,NBCU
IELEM=ISTORU(IBC)
ID=IDIREC(IBC)
CALL ARRAY3(IELEM)
DO IC=1,3
NODE=NORDER(IC)
DISP=PRESU(IBC,IC)
IF(NCHECK(NODE).EQ.ID)GO TO 5

IF(ID.EQ.1)RHS1(NODEP)=RHS1(NODEP)-A11(NODE)*DISP
IF(ID.EQ.1)RHS2(NODEP)=RHS2(NODEP)-A21(NODE)*DISP
IF(ID.EQ.2)RHS1(NODEP)=RHS1(NODEP)-A12(NODE)*DISP
IF(ID.EQ.2)RHS2(NODEP)=RHS2(NODEP)-A22(NODE)*DISP

IF(ID.EQ.1)A11(NODE)=F11(NODE)
IF(ID.EQ.1)A21(NODE)=F21(NODE)
IF(ID.EQ.2)A12(NODE)=F12(NODE)
IF(ID.EQ.2)A22(NODE)=F22(NODE)
NCHECK(NODE)=ID
5 END DO
4 END DO

7771 IF(NBCS.EQ.0)RETURN

!--PRESCRIBED STRESSES: add traction contributions to RHS.
DO IBC=1,NBCS
IELEM=ISTORS(IBC)
CALL ARRAY3(IELEM)
DO IC=1,3
NODE=NORDER(IC)
RHS1(NODEP)=RHS1(NODEP)+B11(IELEM,IC)*XTRAC(IELEM,IC)+B12(IELEM,IC)*YTRAC(IELEM,IC)
RHS2(NODEP)=RHS2(NODEP)+B21(IELEM,IC)*XTRAC(IELEM,IC)+B22(IELEM,IC)*YTRAC(IELEM,IC)
7 END DO
6 END DO

RETURN
END
SUBROUTINE NONSIN(IC)
  use beacon_state
  implicit none
  integer :: ic, ig
  real :: fact, h
!--PURPOSE : TO INTEGRATE NON-SINGULAR KERNELS USING GAUSS QUADRATURE.
DO IG=1,NGAUSS
H=XG(IG)
CALL SHAPE(H)
CALL JACOBI(NODEQ)

GSHAPF(IG)=SHAPF(IC)
IF(IC.EQ.1)THEN
IF(IGEOM.EQ.1)CALL KERAXI
IF(IGEOM.NE.1)CALL KER2D

GUXX(IG)=UXX
GUXY(IG)=UXY
GUYX(IG)=UYX
GUYY(IG)=UYY
GTXX(IG)=TXX
GTXY(IG)=TXY
GTYX(IG)=TYX
GTYY(IG)=TYY

IF(IGEOM.EQ.1)GFACT(IG)=2.*PI*XJACOB*CG(IG)*XQ
IF(IGEOM.NE.1)GFACT(IG)=XJACOB*CG(IG)
ENDIF

FACT=GFACT(IG)*GSHAPF(IG)
A11(NODEQ)=A11(NODEQ)+FACT*GTXX(IG)
A12(NODEQ)=A12(NODEQ)+FACT*GTXY(IG)
A21(NODEQ)=A21(NODEQ)+FACT*GTYX(IG)
A22(NODEQ)=A22(NODEQ)+FACT*GTYY(IG)
B11(IELEMQ,IC)=B11(IELEMQ,IC)+FACT*GUXX(IG)
B12(IELEMQ,IC)=B12(IELEMQ,IC)+FACT*GUXY(IG)
B21(IELEMQ,IC)=B21(IELEMQ,IC)+FACT*GUYX(IG)
B22(IELEMQ,IC)=B22(IELEMQ,IC)+FACT*GUYY(IG)
