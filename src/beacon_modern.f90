DZZKDZ=-2.*XN1*XA*DCDZ/XC**2
DZZEDR=-2.*XA*ZZ*XX9/(XC*XD)
DZZEDZ=PP10*(2.0-(YP-YQ)*DCDZ/XC-(YP-YQ)*DDDZ/XD)
DUXXDR=UXXK*DKDR+UXXE*DEDR+ELLIPK*DRRKDR+ELLIPE*DRREDR
DUXXDZ=UXXK*DKDZ+UXXE*DEDZ+ELLIPK*DRRKDZ+ELLIPE*DRREDZ
DUXYDR=UXYK*DKDR+UXYE*DEDR+ELLIPK*DZRKDR+ELLIPE*DZREDR
DUXYDZ=UXYK*DKDZ+UXYE*DEDZ+ELLIPK*DZRKDZ+ELLIPE*DZREDZ
DUYXDR=UYXK*DKDR+UYXE*DEDR+ELLIPK*DRZKDR+ELLIPE*DRZEDR
DUYXDZ=UYXK*DKDZ+UYXE*DEDZ+ELLIPK*DRZKDZ+ELLIPE*DRZEDZ
DUYYDR=UYYK*DKDR+UYYE*DEDR+ELLIPK*DZZKDR+ELLIPE*DZZEDR
DUYYDZ=UYYK*DKDZ+UYYE*DEDZ+ELLIPK*DZZKDZ+ELLIPE*DZZEDZ
!--
TT1=XA/(XP*XQ*XQ*XC)
TT2=XA/(XP*XQ*XQ*XC*XD)
TT3=XA*(YP-YQ)/(XP*XQ*XC*XD)
TT4=XA/(XP*XQ*XC*XD)
TT5=XA/(XP*XC*XD)
TT6=XA*(YP-YQ)/(XC*XD)
