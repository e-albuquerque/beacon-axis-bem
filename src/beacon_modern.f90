  use beacon_state
  implicit none
  real :: dbdr, dbdz, dcdr, dcdz, dddr, dddz, dedm, dedr, dedz, dfdr, dfdz, dhdr, dhdz, dkdm, dkdr, dkdz, dmdr, dmdz, dndr, dndz, drredr, drredz, drrkdr, drrkdz, drzedr, drzedz, drzkdr, drzkdz, dsdr, dsdz, dt1dr, dt1dz, dt2dr, dt2dz, dt3dr, dt3dz, dt4dr, dt4dz, dt5dr, dt5dz, dt6dr, dt6dz, dt7dr, dt7dz, dt8dr, dt8dz, dte1dr, dte1dz, dte2dr, dte2dz, dte3dr, dte3dz, dte5dr, dte5dz, dte6dr, dte6dz, dte7dr, dte7dz, dtk1dr, dtk1dz, dtk2dr, dtk2dz, dtk3dr, dtk3dz, dtk5dr, dtk5dz, dtk6dr, dtk6dz, dtk7dr, dtk7dz, dvdr, dvdz, dxmdr, dxmdz, dzredr, dzredz, dzrkdr, dzrkdz, dzzedr, dzzedz, dzzkdr, dzzkdz, pp1, pp10, pp4, pp5, pp6, pp7, pp8, pp9, tt1, tt10, tt11, tt12, tt2, tt3, tt4, tt5, tt6, tt7, tt8, tt9, xa, xb, xc, xd, xdc2, xf, xh, xm, xn, xn1, xn2, xn3, xn4, xs, xv, xx1, xx10, xx11, xx12, xx13, xx14, xx15, xx16, xx17, xx18, xx19, xx2, xx20, xx21, xx22, xx23, xx24, xx25, xx26, xx27, xx28, xx29, xx3, xx30, xx31, xx32, xx33, xx34, xx35, xx36, xx37, xx38, xx39, xx4, xx40, xx41, xx42, xx43, xx44, xx45, xx46, xx47, xx48, xx49, xx5, xx50, xx51, xx52, xx53, xx54, xx55, xx56, xx57, xx58, xx59, xx6, xx60, xx61, xx62, xx63, xx7, xx8, xx9, zz
