SUBROUTINE ASSEMB
  use beacon_state
  implicit none
  integer :: i, ibc, ic, icol1, icol2, ielem, ii, irow1, irow2, jj, jmax, node
  real :: dist, h, relxp
!--PURPOSE : TO ASSEMBLE THE A AND B MATRICES.
NEQN=2*NNODES

!--FOR PLANE STRESS CASES, USE EFFECTIVE MATERIAL PROPERTIES.
IF(IGEOM.EQ.3)E=E*(1.0+2.0*XNU)/(1.0+XNU)**2
IF(IGEOM.EQ.3)XNU=XNU/(1.0+XNU)

!--SHEAR MODULUS.
XMU=E/(2.0*(1.0+XNU))

!--TRANSFORM PRESCRIBED STRESSES INTO TRACTIONS.
DO IBC=1,NBCS
IELEM=ISTORS(IBC)
CALL ARRAY3(IELEM)
DO IC=1,3
NODE=NORDER(IC)
H=ZETA(IC)
CALL SHAPE(H)
CALL JACOBI(NODE)
XTRAC(IELEM,IC)=PRESXX(IBC,IC)*XNORM+PRESXY(IBC,IC)*YNORM
YTRAC(IELEM,IC)=PRESXY(IBC,IC)*XNORM+PRESYY(IBC,IC)*YNORM
18 END DO
17 END DO

!--MAXIMUM GEOMETRIC DISTANCE FOR SCALING.
DMAX=0.0
DO II=1,NNODES
DO JJ=1,NNODES
IF(JJ.EQ.II)GO TO 12
DIST=SQRT((X(II)-X(JJ))**2+(Y(II)-Y(JJ))**2)
IF(DIST.GT.DMAX)DMAX=DIST
12 END DO
11 END DO

SCALEF=E/DMAX

!--INITIALISE ARRAYS THAT STORE RHS CONTRIBUTIONS.
DO NODE=1,NNODES
RHS1(NODE)=0.0
RHS2(NODE)=0.0
BN1(NODE)=0.0
BN2(NODE)=0.0
1 END DO

!--TAKE EACH NODE IN TURN AS THE LOAD POINT NODEP.
DO NODEP=1,NNODES
RELXP=0.0
XP=X(NODEP)
YP=Y(NODEP)

!--INITIALISE A/F ARRAYS FOR THIS ROW.
DO NODE=1,NNODES
A11(NODE)=0.0
A12(NODE)=0.0
A21(NODE)=0.0
A22(NODE)=0.0
F11(NODE)=0.0
F12(NODE)=0.0
F21(NODE)=0.0
F22(NODE)=0.0
3 END DO

DO IELEM=1,NELEMS
DO IC=1,3
B11(IELEM,IC)=0.0
B12(IELEM,IC)=0.0
B21(IELEM,IC)=0.0
B22(IELEM,IC)=0.0
9 END DO
8 END DO

!--TAKE EACH ELEMENT IN TURN AS FIELD ELEMENT IELEMQ.
DO IELEMQ=1,NELEMS
CALL ARRAY3(IELEMQ)
DO IC=1,3
NODEQ=NORDER(IC)
RELXP=XP/DMAX

IF(IGEOM.EQ.1.AND.RELXP.LT.1.E-15)CALL PZAXIS(IC)
IF(IGEOM.EQ.1.AND.RELXP.LT.1.E-15)GO TO 5

ISELF=0
IF(NODEP.EQ.NODE1(IELEMQ).OR.NODEP.EQ.NODE2(IELEMQ).OR.NODEP.EQ.NODE3(IELEMQ))ISELF=1

IF(ISELF.EQ.0)CALL NONSIN(IC)
IF(ISELF.EQ.1)CALL SINGU1(IC)
IF(ISELF.EQ.1)CALL SINGU2(IC)
5 END DO
4 END DO

!--COMPLETE DIAGONAL TERMS OF A.
IF(IGEOM.EQ.1)CALL DIAGAX
IF(IGEOM.NE.1)CALL DIAG2D

!--APPLY BOUNDARY CONDITIONS.
CALL BCAPPL

IF(IGEOM.EQ.1.AND.RELXP.LT.1.E-15)A11(NODEP)=1.E-2

!--STORE A11/A12/A21/A22 IN GLOBAL SOLUTION MATRIX A.
IROW1=2*NODEP-1
IROW2=IROW1+1
DO I=1,NNODES
ICOL1=2*I-1
ICOL2=ICOL1+1
A(IROW1,ICOL1)=A11(I)
A(IROW1,ICOL2)=A12(I)
A(IROW2,ICOL1)=A21(I)
A(IROW2,ICOL2)=A22(I)
7 END DO

!--STORE RHS AS LAST COLUMN OF A.
JMAX=NEQN+1
A(IROW1,JMAX)=RHS1(NODEP)
A(IROW2,JMAX)=RHS2(NODEP)
2 END DO

RETURN
END
